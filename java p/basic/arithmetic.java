// package java.basic;

public class arithmetic {
    public static void main(String[] args) {
        
        int a = 4;
        int b = 2;
        System.out.println("Sum " + (a+b));
        System.out.println("Sub " + (a-b));
        System.out.println("Mul " + (a*b));
        System.out.println("Div " + (a/b));
        System.out.println("Rem " + (a%b));
    }
}
