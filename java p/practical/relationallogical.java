public class relationallogical {
  
        public static void main(String[] args) {
            int a = 10, b = 20;
            System.out.println(a > b);
            System.out.println(a < b);
            System.out.println(a == b); 
            System.out.println((a < b) && (b > 15)); 
            System.out.println((a > b) || (b > 15)); 
            System.out.println(!(a < b)); 
        }   
}
